#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_CH32X035_CLOCK_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_CH32X035_CLOCK_H_

#define CH32X035_AHB_PCENR_OFFSET  0
#define CH32X035_APB2_PCENR_OFFSET 1
#define CH32X035_APB1_PCENR_OFFSET 2

#define CH32X035_CLOCK_CONFIG(bus, bit) (((CH32X035_##bus##_PCENR_OFFSET) << 5) | (bit))

/* AHB Peripherals */
#define RCC_AHB_DMA1     CH32X035_CLOCK_CONFIG(AHB, 0)
#define RCC_AHB_SRAM     CH32X035_CLOCK_CONFIG(AHB, 2)
#define RCC_AHB_USBFS    CH32X035_CLOCK_CONFIG(AHB, 12)
// #define RCC_AHB_IO2W     CH32X035_CLOCK_CONFIG(AHB, 13) // Not standard?
#define RCC_AHB_USBPD    CH32X035_CLOCK_CONFIG(AHB, 17)

/* APB2 Peripherals */
#define RCC_APB2_AFIO    CH32X035_CLOCK_CONFIG(APB2, 0)
#define RCC_APB2_GPIOA   CH32X035_CLOCK_CONFIG(APB2, 2)
#define RCC_APB2_GPIOB   CH32X035_CLOCK_CONFIG(APB2, 3)
#define RCC_APB2_GPIOC   CH32X035_CLOCK_CONFIG(APB2, 4)
#define RCC_APB2_ADC1    CH32X035_CLOCK_CONFIG(APB2, 9)
#define RCC_APB2_TIM1    CH32X035_CLOCK_CONFIG(APB2, 11)
#define RCC_APB2_SPI1    CH32X035_CLOCK_CONFIG(APB2, 12)
#define RCC_APB2_USART1  CH32X035_CLOCK_CONFIG(APB2, 14)

/* APB1 Peripherals */
#define RCC_APB1_TIM2    CH32X035_CLOCK_CONFIG(APB1, 0)
#define RCC_APB1_TIM3    CH32X035_CLOCK_CONFIG(APB1, 1)
#define RCC_APB1_WWDG    CH32X035_CLOCK_CONFIG(APB1, 11)
#define RCC_APB1_USART2  CH32X035_CLOCK_CONFIG(APB1, 17)
#define RCC_APB1_USART3  CH32X035_CLOCK_CONFIG(APB1, 18)
#define RCC_APB1_USART4  CH32X035_CLOCK_CONFIG(APB1, 19)
#define RCC_APB1_I2C1    CH32X035_CLOCK_CONFIG(APB1, 21)
#define RCC_APB1_PWR     CH32X035_CLOCK_CONFIG(APB1, 28)

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_CLOCK_CH32X035_CLOCK_H_ */
